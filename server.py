ROOT = Path(__file__).resolve().parent
DB_PATH = Path(os.environ.get("CLUBHOUSE_DB_PATH", ROOT / "clubhouse.sqlite3")).expanduser()
SESSION_IDLE_SECONDS = int(os.environ.get("CLUBHOUSE_SESSION_IDLE_SECONDS", "43200"))
SESSION_MAX_SECONDS = int(os.environ.get("CLUBHOUSE_SESSION_MAX_SECONDS", "604800"))
COOKIE_SECURE = os.environ.get("CLUBHOUSE_COOKIE_SECURE", "0").lower() in {"1", "true", "yes"}
LOGIN_WINDOW_SECONDS = 900
LOGIN_MAX_FAILURES = 8
LOGIN_FAILURES = defaultdict(list)
LOGIN_LOCK = threading.Lock()
WORKSPACE_CLEANED = False
WORKSPACE_CLEANUP_LOCK = threading.Lock()
DEMO_ACCOUNTS = [
    ("admin", "ClubhouseAdmin26!", "u-admin"),
    ("avery", "AveryClub26!", "u-avery"),
    ("jamie", "JamieClub26!", "u-jamie"),
    ("taylor", "TaylorClub26!", "u-taylor"),
]

def connect():
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        try:
            os.chmod(DB_PATH, 0o600)
        except OSError:
            pass
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA busy_timeout=15000")
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("CREATE TABLE IF NOT EXISTS app_state (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS accounts (username TEXT PRIMARY KEY, user_id TEXT NOT NULL, salt TEXT NOT NULL, password_hash TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, created_at REAL NOT NULL, last_seen REAL NOT NULL, expires_at REAL NOT NULL)")
    return conn

def password_hash(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 180000).hex()

def ensure_accounts():
    with connect() as conn:
        count = conn.execute("SELECT COUNT(*) FROM accounts").fetchone()[0]
        if count == 0:
            for username, password, user_id in DEMO_ACCOUNTS:
                salt = secrets.token_hex(16)
                conn.execute("INSERT INTO accounts(username,user_id,salt,password_hash) VALUES(?,?,?,?)",
                             (username, user_id, salt, password_hash(password, salt)))
    clean_legacy_sample_activity()

def clean_legacy_sample_activity():
    """Remove only activity records generated by the old local demo seeder."""
    global WORKSPACE_CLEANED
    if WORKSPACE_CLEANED:
        return
    with WORKSPACE_CLEANUP_LOCK:
        if WORKSPACE_CLEANED:
            return
        with connect() as conn:
            row = conn.execute("SELECT payload FROM app_state WHERE id=1").fetchone()
            if row:
                state = json.loads(row[0])
                demo_interactions = {"i-1", "i-2", "i-3", "i-4", "i-5"}
                demo_meetings = {"m-1", "m-2", "m-3"}
                interactions = state.get("interactions", [])
                meetings = state.get("meetings", [])
                state["interactions"] = [item for item in interactions if item.get("id") not in demo_interactions and not str(item.get("id", "")).startswith("sample-cowboys-")]
                state["meetings"] = [item for item in meetings if item.get("id") not in demo_meetings and not str(item.get("id", "")).startswith("sample-cowboys-")]
                if len(state["interactions"]) != len(interactions) or len(state["meetings"]) != len(meetings):
                    conn.execute("UPDATE app_state SET payload=? WHERE id=1", (json.dumps(state),))
        WORKSPACE_CLEANED = True

def session_actor(handler):
    cookie = SimpleCookie(handler.headers.get("Cookie", ""))
    morsel = cookie.get("clubhouse_session")
    if not morsel:
        return None
    now = time.time()
    token_hash = hashlib.sha256(morsel.value.encode()).hexdigest()
    with connect() as conn:
        conn.execute("DELETE FROM sessions WHERE expires_at <= ?", (now,))
        row = conn.execute("SELECT user_id,created_at FROM sessions WHERE token_hash=? AND expires_at>?", (token_hash, now)).fetchone()
        if not row:
            return None
        absolute_expiry = row[1] + SESSION_MAX_SECONDS
        next_expiry = min(now + SESSION_IDLE_SECONDS, absolute_expiry)
        conn.execute("UPDATE sessions SET last_seen=?,expires_at=? WHERE token_hash=?", (now, next_expiry, token_hash))
        return row[0]

def create_session(user_id):
    token = secrets.token_urlsafe(32)
    now = time.time()
    digest = hashlib.sha256(token.encode()).hexdigest()
    with connect() as conn:
        conn.execute("DELETE FROM sessions WHERE expires_at <= ?", (now,))
        conn.execute("INSERT INTO sessions(token_hash,user_id,created_at,last_seen,expires_at) VALUES(?,?,?,?,?)",
                     (digest, user_id, now, now, min(now + SESSION_IDLE_SECONDS, now + SESSION_MAX_SECONDS)))
    return token

def revoke_session(handler):
    cookie = SimpleCookie(handler.headers.get("Cookie", ""))
    morsel = cookie.get("clubhouse_session")
    if morsel:
        digest = hashlib.sha256(morsel.value.encode()).hexdigest()
        with connect() as conn:
            conn.execute("DELETE FROM sessions WHERE token_hash=?", (digest,))

def login_is_limited(remote):
    now = time.time()
    with LOGIN_LOCK:
        failures = [stamp for stamp in LOGIN_FAILURES[remote] if now - stamp < LOGIN_WINDOW_SECONDS]
        LOGIN_FAILURES[remote] = failures
        return len(failures) >= LOGIN_MAX_FAILURES

def note_login_failure(remote):
    now = time.time()
    with LOGIN_LOCK:
        LOGIN_FAILURES[remote] = [stamp for stamp in LOGIN_FAILURES[remote] if now - stamp < LOGIN_WINDOW_SECONDS] + [now]

def clear_login_failures(remote):
    with LOGIN_LOCK:
        LOGIN_FAILURES.pop(remote, None)

class RequestTooLarge(ValueError):
    pass

def account_user(username):
    with connect() as conn:
        row = conn.execute("SELECT user_id,salt,password_hash FROM accounts WHERE username=?", (username,)).fetchone()
    return row

def get_state():
    with connect() as conn:
        row = conn.execute("SELECT payload FROM app_state WHERE id=1").fetchone()
    return json.loads(row[0]) if row else None

def put_state(state):
    with connect() as conn:
        conn.execute("INSERT INTO app_state(id,payload) VALUES(1,?) ON CONFLICT(id) DO UPDATE SET payload=excluded.payload", (json.dumps(state),))

def validate_state_shape(state):
    if not isinstance(state, dict):
        raise ValueError("Workspace state must be an object")
    limits = {"users": 200, "clubs": 500, "interactions": 20000, "meetings": 20000}
    for key, maximum in limits.items():
        items = state.get(key)
        if not isinstance(items, list) or len(items) > maximum or any(not isinstance(item, dict) for item in items):
            raise ValueError(f"Invalid workspace {key}")
    users = {item.get("id") for item in state["users"]}
    clubs = {item.get("id") for item in state["clubs"]}
    if not users or None in users or None in clubs:
        raise ValueError("Workspace users and clubs need identifiers")
    for user in state["users"]:
        if user.get("role") not in {"Admin", "User"}:
            raise ValueError("Invalid workspace role")
    def valid_date(value, required=True):
        if not value and not required:
            return True
        try:
            calendar_date.fromisoformat(value)
            return True
        except (TypeError, ValueError):
            return False
    for item in state["interactions"]:
        if item.get("clubId") not in clubs or not item.get("id") or item.get("owner") not in users:
            raise ValueError("Interaction references an unknown club or user")
        if not valid_date(item.get("date")) or not isinstance(item.get("summary", ""), str) or len(item.get("summary", "")) > 12000:
            raise ValueError("Interaction date or summary is invalid")
        for follow in item.get("followups", []):
            if not isinstance(follow, dict) or follow.get("status") not in {"Open", "Done", "Canceled"}:
                raise ValueError("Invalid next step")
            if follow.get("owner") not in users or not valid_date(follow.get("due"), required=False):
                raise ValueError("Next step references an unknown user or invalid due date")
    for meeting in state["meetings"]:
        if meeting.get("clubId") not in clubs or not meeting.get("id") or meeting.get("owner") not in users:
            raise ValueError("Meeting references an unknown club or user")
        if meeting.get("status") not in {"Planned", "Completed", "Canceled"} or not valid_date(meeting.get("date")):
            raise ValueError("Meeting date or status is invalid")
        if meeting.get("time") and not re.fullmatch(r"(?:[01]\d|2[0-3]):[0-5]\d", meeting["time"]):
            raise ValueError("Meeting time is invalid")
    if not isinstance(state.get("contracts", {}), dict):
        raise ValueError("Invalid contract records")

def save_state_transaction(incoming, actor):
    validate_state_shape(incoming)
    with connect() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = conn.execute("SELECT payload FROM app_state WHERE id=1").fetchone()
        old = json.loads(row[0]) if row else None
        if old is None:
            if not any(u.get("id") == actor and u.get("role") == "Admin" for u in incoming.get("users", [])):
                raise ValueError("Set up the workspace using an administrator account")
            merged = incoming
        else:
            merged = validate_and_merge(old, incoming, actor)
        merged["activeUser"] = actor
        merged["clubs"] = [{k: v for k, v in club.items() if k != "assignments"} for club in merged.get("clubs", [])]
        conn.execute("INSERT INTO app_state(id,payload) VALUES(1,?) ON CONFLICT(id) DO UPDATE SET payload=excluded.payload", (json.dumps(merged),))
    return merged

def visible_state(state, actor):
    result = json.loads(json.dumps(state))
    person = next((u for u in state.get("users", []) if u["id"] == actor), None)
    if not person:
        raise ValueError("Unknown workspace user")
    result["activeUser"] = actor
    # Contract information is private to its owner unless the signed-in user is an admin.
    if person.get("role") != "Admin":
        # Keep the main activity payload private to its creator. Next steps
        # assigned to this user are provided separately without meeting notes.
        all_interactions = result.get("interactions", [])
        result["assignedFollowups"] = [
            {"id": follow.get("id"), "interactionId": item.get("id"), "clubId": item.get("clubId"),
             "interactionOwner": item.get("owner"), "description": follow.get("description", ""),
             "owner": follow.get("owner"), "due": follow.get("due", ""), "status": follow.get("status", "Open")}
            for item in all_interactions if item.get("owner") != actor
            for follow in item.get("followups", []) if follow.get("owner") == actor
        ]
        result["interactions"] = [item for item in all_interactions if item.get("owner") == actor]
        result["meetings"] = [m for m in result.get("meetings", []) if m.get("owner") == actor]
        contracts = result.get("contracts", {})
        result["contracts"] = {actor: contracts[actor]} if actor in contracts else {}
    # All signed-in users share the club directory. Remove legacy assignment
    # metadata so old demo data cannot imply restrictions.
    for club in result.get("clubs", []):
        club.pop("assignments", None)
    return result

def update_followup_status(interaction_id, followup_id, status, actor):
    if status not in {"Open", "Done", "Canceled"}:
        raise ValueError("Invalid next-step status")
    with connect() as conn:
        conn.execute("BEGIN IMMEDIATE")
        row = conn.execute("SELECT payload FROM app_state WHERE id=1").fetchone()
        if not row:
            raise ValueError("Workspace is not initialized")
        state = json.loads(row[0])
        users = {u.get("id"): u for u in state.get("users", [])}
        person = users.get(actor)
        interaction = next((i for i in state.get("interactions", []) if i.get("id") == interaction_id), None)
        followup = next((f for f in (interaction or {}).get("followups", []) if f.get("id") == followup_id), None)
        if not person or not interaction or not followup:
            raise ValueError("Next step not found")
        if person.get("role") != "Admin" and followup.get("owner") != actor and interaction.get("owner") != actor:
            raise ValueError("You can only update your own next steps")
        followup["status"] = status
        conn.execute("UPDATE app_state SET payload=? WHERE id=1", (json.dumps(state),))

def same(a, b):
    return json.dumps(a, sort_keys=True) == json.dumps(b, sort_keys=True)

def validate_and_merge(old, incoming, actor):
    users = {u["id"]: u for u in old.get("users", [])}
    person = users.get(actor)
    if not person:
        raise ValueError("Unknown workspace user")
    if person.get("role") == "Admin":
        merged = incoming
        merged["activeUser"] = actor
        merged["clubs"] = [{k: v for k, v in club.items() if k != "assignments"} for club in incoming.get("clubs", [])]
        return merged

    club_ids = {c["id"] for c in old.get("clubs", [])}
    for club in incoming.get("clubs", []):
        if club["id"] not in club_ids:
            raise ValueError("Unknown club")
    if not same(incoming.get("users", []), old.get("users", [])):
        raise ValueError("Only an admin can manage users")

    merged = json.loads(json.dumps(old))
    merged["clubs"] = [{k: v for k, v in club.items() if k != "assignments"} for club in old.get("clubs", [])]
    old_interactions = {x["id"]: x for x in old.get("interactions", [])}
    merged_interactions = {x["id"]: x for x in old.get("interactions", [])}
    for item in incoming.get("interactions", []):
        if item.get("clubId") not in club_ids:
            raise ValueError("Unknown club")
        previous = old_interactions.get(item["id"])
        if previous is None:
            if item.get("owner") != actor:
                raise ValueError("You can only create interactions for yourself")
            merged_interactions[item["id"]] = item
        elif previous.get("owner") == actor:
            if item.get("owner") != actor:
                raise ValueError("Interaction ownership cannot be transferred")
            merged_interactions[item["id"]] = item
        else:
            normalized = json.loads(json.dumps(item))
            before_f = {f["id"]: f for f in previous.get("followups", [])}
            after_f = {f["id"]: f for f in normalized.get("followups", [])}
            allowed_statuses = {}
            for fid, prior in before_f.items():
                changed = after_f.get(fid)
                if changed and prior.get("owner") == actor and changed.get("owner") == actor:
                    if changed.get("status") not in {"Open", "Done", "Canceled"}:
                        raise ValueError("Invalid follow-up status")
                    allowed_statuses[fid] = changed.get("status")
                    changed["status"] = prior.get("status")
            if not same(previous, normalized):
                raise ValueError("You can only edit interactions you created")
            authorized_update = json.loads(json.dumps(previous))
            for follow in authorized_update.get("followups", []):
                if follow.get("id") in allowed_statuses:
                    follow["status"] = allowed_statuses[follow["id"]]
            merged_interactions[item["id"]] = authorized_update
    merged["interactions"] = list(merged_interactions.values())

    old_meetings = {m["id"]: m for m in old.get("meetings", [])}
    merged_meetings = {m["id"]: m for m in old.get("meetings", [])}
    for item in incoming.get("meetings", []):
        if item.get("clubId") not in club_ids:
            raise ValueError("Unknown club")
        previous = old_meetings.get(item["id"])
        if previous is None:
            if item.get("owner") != actor:
                raise ValueError("You can only create meetings for yourself")
        else:
            if previous.get("owner") != actor and not same(previous, item):
                raise ValueError("You can only change meetings you created")
            if item.get("owner") != previous.get("owner"):
                raise ValueError("Meeting ownership cannot be transferred")
        if item.get("status") not in {"Planned", "Completed", "Canceled"}:
            raise ValueError("Invalid meeting status")
        merged_meetings[item["id"]] = item
    merged["meetings"] = list(merged_meetings.values())
    merged["activeUser"] = actor
    return merged

class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        ensure_accounts()
        super().__init__(*args, directory=str(ROOT), **kwargs)

    def log_message(self, fmt, *args):
        print("[clubhouse] " + fmt % args)

    def end_headers(self):
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("X-Frame-Options", "DENY")
        self.send_header("Referrer-Policy", "strict-origin-when-cross-origin")
        self.send_header("Permissions-Policy", "camera=(), microphone=(), geolocation=()")
        self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src 'self' data: https://a.espncdn.com; connect-src 'self'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'; object-src 'none'")
        if COOKIE_SECURE:
            self.send_header("Strict-Transport-Security", "max-age=31536000; includeSubDomains")
        super().end_headers()

    def same_origin_request(self):
        origin = self.headers.get("Origin")
        if origin:
            parsed = urlparse(origin)
            return parsed.scheme in {"http", "https"} and parsed.netloc.lower() == self.headers.get("Host", "").lower()
        return self.headers.get("Sec-Fetch-Site", "").lower() != "cross-site"

    def read_json(self, limit=2_000_000):
        if "application/json" not in self.headers.get("Content-Type", "").lower():
            raise ValueError("Content-Type must be application/json")
        length = int(self.headers.get("Content-Length", "0"))
        if length < 0 or length > limit:
            raise RequestTooLarge("Request body is too large")
        data = json.loads(self.rfile.read(length))
        if not isinstance(data, dict):
            raise ValueError("Request body must be a JSON object")
        return data

    def send_json(self, status, payload, headers=None):
        body = json.dumps(payload).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for name, value in (headers or {}).items():
            self.send_header(name, value)
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        url = urlparse(self.path)
        if url.path == "/healthz":
            return self.send_json(200, {"ok": True})
        if url.path == "/api/session":
            actor = session_actor(self)
            if not actor:
                return self.send_json(200, {"authenticated": False})
            state = get_state()
            return self.send_json(200, {"authenticated": True, "actor": actor, "state": visible_state(state, actor) if state else None})
        if url.path == "/api/state":
            actor = session_actor(self)
            if not actor:
                return self.send_json(401, {"error": "Sign in to continue"})
            state = get_state()
            if state is None:
                return self.send_json(200, {"state": None})
            try:
                return self.send_json(200, {"state": visible_state(state, actor)})
            except ValueError as exc:
                return self.send_json(403, {"error": str(exc)})
        return super().do_GET()

    def do_POST(self):
        path = urlparse(self.path).path
        if not self.same_origin_request():
            return self.send_json(403, {"error": "Cross-origin request rejected"})
        if path == "/api/login":
            remote = self.client_address[0]
            if login_is_limited(remote):
                return self.send_json(429, {"error": "Too many unsuccessful sign-in attempts. Try again in 15 minutes."}, {"Retry-After": str(LOGIN_WINDOW_SECONDS)})
            try:
                data = self.read_json(8_000)
                username = data.get("username", "")
                password = data.get("password", "")
                if not isinstance(username, str) or not isinstance(password, str):
                    return self.send_json(400, {"error": "Username and password must be text"})
                row = account_user(username.strip().lower())
                candidate_hash = password_hash(password, row[1] if row else "00" * 16)
                if not row or not hmac.compare_digest(candidate_hash, row[2]):
                    note_login_failure(remote)
                    return self.send_json(401, {"error": "Username or password is incorrect"})
                clear_login_failures(remote)
                token = create_session(row[0])
                state = get_state()
                cookie = f"clubhouse_session={token}; HttpOnly; SameSite=Lax; Path=/; Max-Age={SESSION_MAX_SECONDS}"
                if COOKIE_SECURE:
                    cookie += "; Secure"
                return self.send_json(200, {"authenticated": True, "actor": row[0], "state": visible_state(state, row[0]) if state else None},
                                      {"Set-Cookie": cookie})
            except RequestTooLarge as exc:
                return self.send_json(413, {"error": str(exc)})
            except (ValueError, KeyError, TypeError, json.JSONDecodeError):
                return self.send_json(400, {"error": "Invalid sign-in request"})
        if path == "/api/logout":
            revoke_session(self)
            expired = "clubhouse_session=; HttpOnly; SameSite=Lax; Path=/; Max-Age=0" + ("; Secure" if COOKIE_SECURE else "")
            return self.send_json(200, {"ok": True}, {"Set-Cookie": expired})
        if path == "/api/followup":
            actor = session_actor(self)
            if not actor:
                return self.send_json(401, {"error": "Sign in to continue"})
            try:
                data = self.read_json(8_000)
                update_followup_status(data.get("interactionId"), data.get("followupId"), data.get("status"), actor)
                return self.send_json(200, {"ok": True})
            except RequestTooLarge as exc:
                return self.send_json(413, {"error": str(exc)})
            except (ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
                return self.send_json(403, {"error": str(exc)})
        if path != "/api/state":
            return self.send_json(404, {"error": "Not found"})
        try:
            actor = session_actor(self)
            if not actor:
                return self.send_json(401, {"error": "Sign in to continue"})
            data = self.read_json()
            incoming = data["state"]
            if not isinstance(incoming, dict):
                raise ValueError("Workspace state is required")
            save_state_transaction(incoming, actor)
            return self.send_json(200, {"ok": True})
        except RequestTooLarge as exc:
            return self.send_json(413, {"error": str(exc)})
        except (ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
            return self.send_json(403, {"error": str(exc)})

