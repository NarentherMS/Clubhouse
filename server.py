def connect():
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        try:
            os.chmod(DB_PATH, 0o600)
        except OSError:
            pass
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA busy_timeout=15000")
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("CREATE TABLE IF NOT EXISTS app_state (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS accounts (username TEXT PRIMARY KEY, user_id TEXT NOT NULL, salt TEXT NOT NULL, password_hash TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, created_at REAL NOT NULL, last_seen REAL NOT NULL, expires_at REAL NOT NULL)")
    return conn

def password_hash(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 180000).hex()

def ensure_accounts():
    with connect() as conn:
        count = conn.execute("SELECT COUNT(*) FROM accounts").fetchone()[0]
        if count == 0:
            for username, password, user_id in DEMO_ACCOUNTS:
                salt = secrets.token_hex(16)
                conn.execute("INSERT INTO accounts(username,user_id,salt,password_hash) VALUES(?,?,?,?)",
                             (username, user_id, salt, password_hash(password, salt)))
    clean_legacy_sample_activity()

def clean_legacy_sample_activity():
    """Remove only activity records generated by the old local demo seeder."""
    global WORKSPACE_CLEANED
    if WORKSPACE_CLEANED:
        return
    with WORKSPACE_CLEANUP_LOCK:
        if WORKSPACE_CLEANED:
            return
        with connect() as conn:
            row = conn.execute("SELECT payload FROM app_state WHERE id=1").fetchone()
            if row:
                state = json.loads(row[0])
                demo_interactions = {"i-1", "i-2", "i-3", "i-4", "i-5"}
                demo_meetings = {"m-1", "m-2", "m-3"}
                interactions = state.get("interactions", [])
                meetings = state.get("meetings", [])
                state["interactions"] = [item for item in interactions if item.get("id") not in demo_interactions and not str(item.get("id", "")).startswith("sample-cowboys-")]
                state["meetings"] = [item for item in meetings if item.get("id") not in demo_meetings and not str(item.get("id", "")).startswith("sample-cowboys-")]
                if len(state["interactions"]) != len(interactions) or len(state["meetings"]) != len(meetings):
                    conn.execute("UPDATE app_state SET payload=? WHERE id=1", (json.dumps(state),))
        WORKSPACE_CLEANED = True

def session_actor(handler):
    cookie = SimpleCookie(handler.headers.get("Cookie", ""))
    morsel = cookie.get("clubhouse_session")
    if not morsel:
        return None
    now = time.time()
    token_hash = hashlib.sha256(morsel.value.encode()).hexdigest()
    with connect() as conn:
        conn.execute("DELETE FROM sessions WHERE expires_at <= ?", (now,))
        row = conn.execute("SELECT user_id,created_at FROM sessions WHERE token_hash=? AND expires_at>?", (token_hash, now)).fetchone()
        if not row:
            return None
        absolute_expiry = row[1] + SESSION_MAX_SECONDS
        next_expiry = min(now + SESSION_IDLE_SECONDS, absolute_expiry)
        conn.execute("UPDATE sessions SET last_seen=?,expires_at=? WHERE token_hash=?", (now, next_expiry, token_hash))
        return row[0]

def create_session(user_id):
    token = secrets.token_urlsafe(32)
    now = time.time()
    digest = hashlib.sha256(token.encode()).hexdigest()
    with connect() as conn:
        conn.execute("DELETE FROM sessions WHERE expires_at <= ?", (now,))
        conn.execute("INSERT INTO sessions(token_hash,user_id,created_at,last_seen,expires_at) VALUES(?,?,?,?,?)",
                     (digest, user_id, now, now, min(now + SESSION_IDLE_SECONDS, now + SESSION_MAX_SECONDS)))
    return token

def revoke_session(handler):
    cookie = SimpleCookie(handler.headers.get("Cookie", ""))
    morsel = cookie.get("clubhouse_session")
    if morsel:
        digest = hashlib.sha256(morsel.value.encode()).hexdigest()
        with connect() as conn:
            conn.execute("DELETE FROM sessions WHERE token_hash=?", (digest,))

def login_is_limited(remote):
    now = time.time()
    with LOGIN_LOCK:
        failures = [stamp for stamp in LOGIN_FAILURES[remote] if now - stamp < LOGIN_WINDOW_SECONDS]
        LOGIN_FAILURES[remote] = failures
        return len(failures) >= LOGIN_MAX_FAILURES

def note_login_failure(remote):
    now = time.time()
    with LOGIN_LOCK:
        LOGIN_FAILURES[remote] = [stamp for stamp in LOGIN_FAILURES[remote] if now - stamp < LOGIN_WINDOW_SECONDS] + [now]

def clear_login_failures(remote):
    with LOGIN_LOCK:
        LOGIN_FAILURES.pop(remote, None)

