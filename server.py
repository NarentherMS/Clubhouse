def restore_workspace_snapshot(snapshot_path=None):
    """Load committed data on first run; never replace an existing local database."""
    snapshot = Path(snapshot_path) if snapshot_path is not None else ROOT / 'workspace-data.sqlite3'
    if DB_PATH.exists() or not snapshot.exists():
        return False
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(prefix='.workspace-import-', suffix='.sqlite3', dir=DB_PATH.parent)
    os.close(descriptor)
    temporary = Path(temporary_name)
    try:
        with closing(sqlite3.connect(snapshot.resolve().as_uri() + '?mode=ro', uri=True)) as source:
            with closing(sqlite3.connect(temporary)) as destination:
                source.backup(destination)
                destination.execute('PRAGMA journal_mode=DELETE')
                if destination.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
                    raise ValueError('The portable workspace failed its integrity check')
        os.chmod(temporary, 0o600)
        try:
            os.link(temporary, DB_PATH)
        except FileExistsError:
            return False
    finally:
        temporary.unlink(missing_ok=True)
    return True


def connect():
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        try:
            os.chmod(DB_PATH, 0o600)
        except OSError:
            pass
    conn = sqlite3.connect(DB_PATH)
    conn.execute("PRAGMA busy_timeout=15000")
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("CREATE TABLE IF NOT EXISTS app_state (id INTEGER PRIMARY KEY CHECK(id=1), payload TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS accounts (username TEXT PRIMARY KEY, user_id TEXT NOT NULL, salt TEXT NOT NULL, password_hash TEXT NOT NULL)")
    conn.execute("CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, created_at REAL NOT NULL, last_seen REAL NOT NULL, expires_at REAL NOT NULL)")
    return conn

def password_hash(password, salt):
    return hashlib.pbkdf2_hmac("sha256", password.encode(), bytes.fromhex(salt), 180000).hex()

